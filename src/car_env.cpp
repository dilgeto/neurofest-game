bool CarEnv::onTrack(double worldX, double worldY) const {
    double colF = (worldX + TRACK_SCALE * TRACK_SIZE / 2.0) / TRACK_SCALE;
    double rowF = (-worldY + TRACK_SCALE * TRACK_SIZE / 2.0) / TRACK_SCALE;
    if (colF <= 0.0 || colF >= TRACK_SIZE || rowF <= 0.0 || rowF >= TRACK_SIZE) return false;
    int col = static_cast<int>(colF);
    int row = static_cast<int>(rowF);
    return TRACK_ROWS[row][col] == '#';
}

double CarEnv::lidarDistance(double directionOffset) const {
    double dirX = std::cos(mu_ + directionOffset) * LIDAR_STEP_SIZE;
    double dirY = std::sin(mu_ + directionOffset) * LIDAR_STEP_SIZE;
    double distance = LIDAR_NUM_STEPS * LIDAR_STEP_SIZE;
    for (int i = 0; i < LIDAR_NUM_STEPS; ++i) {
        if (!onTrack(x_ + dirX * i, y_ + dirY * i)) {
            distance = i * LIDAR_STEP_SIZE;
            break;
        }
    }
    return distance / (LIDAR_NUM_STEPS * LIDAR_STEP_SIZE);
}

void CarEnv::reset(std::mt19937& rng) {
    std::uniform_real_distribution<double> posDist(-BOUND, BOUND);
    std::uniform_real_distribution<double> muDist(-M_PI, M_PI);
    do {
        x_ = posDist(rng);
        y_ = posDist(rng);
        mu_ = muDist(rng);
    } while (!onTrack(x_, y_));
    vx_ = vy_ = omega_ = 0.0;
    stepCount_ = 0;
}

std::array<double, 9> CarEnv::observe() const {
    constexpr double DEG20 = 20.0 * M_PI / 180.0;
    return {
        x_, y_, mu_, vx_, vy_, omega_,
        lidarDistance(-DEG20), lidarDistance(0.0), lidarDistance(DEG20)
    };
}

void CarEnv::step(double throttleBrake, double steering, std::mt19937& rng) {
    double throttle = std::clamp(throttleBrake, -1.0, 1.0);
    double delta = std::clamp(steering, -1.0, 1.0);

    double alphaF = std::atan2(vy_ + LF * omega_, vx_) - delta;
    double alphaR = std::atan2(vy_ - LR * omega_, vx_);
    double fnF = LR / (LF + LR) * M * G;
    double fnR = LF / (LF + LR) * M * G;
    bool moving = vx_ > VT || vy_ > VT;
    double fyF = moving ? fnF * TF_D * std::sin(TF_C * std::atan(TF_B * (-alphaF))) : 0.0;
    double fyR = moving ? fnR * TR_D * std::sin(TR_C * std::atan(TR_B * (-alphaR))) : 0.0;

    double fx = CM * throttle - CR0 - CR2 * vx_ * vx_;

    double nextX = x_ + DT * (std::cos(mu_) * vx_ - std::sin(mu_) * vy_);
    double nextY = y_ + DT * (std::sin(mu_) * vx_ + std::cos(mu_) * vy_);
    double nextMu = mu_ + DT * omega_;
    double nextVx = vx_ + DT * (1.0 / M * (fx - fyF * std::sin(delta)) + omega_ * vy_);
    double nextVy = vy_ + DT * (1.0 / M * (fyF * std::cos(delta) + fyR) - omega_ * vx_);
    double nextOmega = omega_ + DT * (1.0 / INERTIA * (fyF * LF * std::cos(delta) - fyR * LR));

    x_ = nextX; y_ = nextY; mu_ = nextMu;
    vx_ = nextVx; vy_ = nextVy; omega_ = nextOmega;
    ++stepCount_;

    bool terminated = !onTrack(x_, y_);
    if (terminated || stepCount_ >= EPISODE_STEP_LIMIT) reset(rng);
}

void CarEnv::ensureTrackTexture() const {
    if (trackTextureReady_) return;
    Image img = GenImageColor(TRACK_SIZE, TRACK_SIZE, WHITE);
    for (int row = 0; row < TRACK_SIZE; ++row) {
        for (int col = 0; col < TRACK_SIZE; ++col) {
            Color c = (TRACK_ROWS[row][col] == '#') ? Color{60, 60, 66, 255} : Color{230, 230, 232, 255};
            ImageDrawPixel(&img, col, row, c);
        }
    }
    trackTexture_ = LoadTextureFromImage(img);
    UnloadImage(img);
    trackTextureReady_ = true;
}

void CarEnv::draw(Rectangle bounds) const {
    ensureTrackTexture();

    float scale = std::min(bounds.width, bounds.height) / static_cast<float>(2.0 * BOUND);
    Vector2 origin = { bounds.x + bounds.width / 2.0f, bounds.y + bounds.height / 2.0f };
    Rectangle dest = {
        origin.x - static_cast<float>(BOUND) * scale, origin.y - static_cast<float>(BOUND) * scale,
        static_cast<float>(2.0 * BOUND) * scale, static_cast<float>(2.0 * BOUND) * scale
    };
    DrawTexturePro(trackTexture_, { 0, 0, static_cast<float>(TRACK_SIZE), static_cast<float>(TRACK_SIZE) },
        dest, { 0, 0 }, 0.0f, WHITE);

    Vector2 carScreen = { origin.x + static_cast<float>(x_) * scale, origin.y - static_cast<float>(y_) * scale };

    constexpr double DEG20 = 20.0 * M_PI / 180.0;
    double directions[3] = { -DEG20, 0.0, DEG20 };
    for (double dir : directions) {
        double dist = lidarDistance(dir) * (LIDAR_NUM_STEPS * LIDAR_STEP_SIZE);
        Vector2 rayEnd = {
            carScreen.x + static_cast<float>(dist * std::cos(mu_ + dir)) * scale,
            carScreen.y - static_cast<float>(dist * std::sin(mu_ + dir)) * scale
        };
        DrawLineEx(carScreen, rayEnd, 1.5f, Fade(Color{60, 120, 220, 255}, 0.6f));
    }

    Vector2 heading = {
        carScreen.x + 14.0f * static_cast<float>(std::cos(mu_)),
        carScreen.y - 14.0f * static_cast<float>(std::sin(mu_))
    };
    DrawLineEx(carScreen, heading, 3.0f, Color{220, 90, 70, 255});
    DrawCircleV(carScreen, 6.0f, Color{220, 90, 70, 255});

    DrawText(TextFormat("Paso episodio: %d / %d", stepCount_, EPISODE_STEP_LIMIT),
        static_cast<int>(bounds.x), static_cast<int>(bounds.y + bounds.height - 20), 18, DARKGRAY);
}
